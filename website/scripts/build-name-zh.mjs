async function translateName(name) {
  const params = new URLSearchParams({ client: "gtx", sl: "ja", tl: "zh-TW", dt: "t", q: name });
  const response = await fetch(`https://translate.googleapis.com/translate_a/single?${params}`);
  if (!response.ok) throw new Error(`Translation failed for ${name}: ${response.status}`);
  const result = await response.json();
  return result[0].map((segment) => segment[0]).join("").trim();
}

