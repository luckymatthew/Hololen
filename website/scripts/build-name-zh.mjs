if (missing.length > 0) console.log(`Online fallback for: ${missing.join("、")}`);

let cursor = 0;
const workers = Array.from({ length: 6 }, async () => {
  while (cursor < missing.length) {
    const name = missing[cursor++];
    translations[name] = (await translateName(name)) || name;
  }
});
await Promise.all(workers);

const sorted = Object.fromEntries(
  Object.entries(translations)
    .filter(([name]) => uniqueNames.includes(name))
    .sort(([left], [right]) => left.localeCompare(right, "ja")),
);
fs.writeFileSync(outputPath, `${JSON.stringify(sorted, null, 2)}\n`);

for (const card of payload.cards) {
  const translatedName = sorted[card.jpName] || card.name || card.jpName || card.number;
  card.name = card.simOnly && /HoloSim 異圖/.test(card.name)
    ? `${translatedName}（HoloSim 異圖）`
    : translatedName;
}

payload.meta.traditionalChineseCards = payload.cards.filter((card) => sorted[card.jpName]).length;
payload.meta.note = "卡名採繁中翻譯，EN／ID 成員採官方英文名；技能為非官方繁中閱讀翻譯，正式對戰與裁定以官方日文資料為準。";
fs.writeFileSync(cardsPath, JSON.stringify(payload));
console.log(`Wrote ${Object.keys(sorted).length} localized card names to ${outputPath}`);
