export function hbp09Translation(card, value, path = null) {
  if (!card || typeof value !== "string") return null;
  const entry = hbp09Translations.cards[card.number];
  if (!entry) return null;
  const match = entry.fields.find(field =>
    field.original === value && (path == null || field.path === path));
  return match ? match.translation : null;
}

export function hbp09TranslationReview(card) {
  const entry = hbp09Translations.cards[card?.number];
  if (!entry) return null;
  return {
    status: entry.translationStatus,
    humanReviewStatus: entry.humanReviewStatus,
    sourceUrl: entry.sourceUrl,
    gameplay: "Translation is display-only; it does not establish engine support.",
  };
}

export function hbp09TagText(tag) {
  const raw = String(tag ?? "");
  return hbp09Translations.tagDisplay[raw] ?? raw;
}
